// Deno does not infer the existing protocol.d.ts next to the JS bundle.
// Emit its new admin types from the same source rather than hand-copying schemas.
import ts from 'typescript';
import { writeFileSync } from 'node:fs';

const roots = ['src/protocol/admin-authority.ts', 'src/protocol/admin-policy.ts', 'src/protocol/admin-routine.ts', 'src/protocol/household-objects.ts', 'src/protocol/household-tool-registry.ts'];
const program = ts.createProgram(roots, {
  declaration: true, emitDeclarationOnly: true, strict: true,
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext, skipLibCheck: true,
});
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) {
  process.stderr.write(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: name => name, getCurrentDirectory: () => process.cwd(),
    getNewLine: () => '\n',
  }));
  process.exit(1);
}
const emitted = new Set();
program.emit(undefined, (name, contents) => {
  for (const base of ['admin-authority', 'admin-policy', 'admin-routine', 'workspace-events', 'events', 'admin-routine-events', 'household-objects', 'household-object-events', 'household-object-policy', 'household-tool-registry', 'reducer']) {
    if (name.endsWith(`/protocol/${base}.d.ts`)) {
      writeFileSync(`supabase/functions/_shared/${base}.d.ts`,
        '// GENERATED by scripts/build-admin-types.mjs; do not hand-edit.\n' +
        contents.replace(/(['"])\.\/(admin-policy|admin-authority|admin-routine|workspace-events|events|admin-routine-events|household-objects|household-object-events|household-object-policy|household-tool-registry|brain-version-window|reducer|idempotency|commands)\.js\1/g,
          (_, quote, module) => `${quote}./${module}.d.ts${quote}`));
      emitted.add(base);
    }
  }
});
if (emitted.size !== 11) throw new Error('missing admin declaration output');
