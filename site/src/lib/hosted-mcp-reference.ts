type InputSchema = { properties?: Record<string, unknown>; required?: readonly string[]; anyOf?: readonly { required?: readonly string[] }[] };
export function toolArguments(schema: InputSchema): string {
  const required = [...(schema.required ?? [])];
  const alternatives = schema.anyOf?.map(option => option.required?.join(" + ")).filter(Boolean) ?? [];
  const parts = [...required, ...(alternatives.length ? [`(${alternatives.join(" or ")})`] : [])];
  const alternativeKeys = new Set(schema.anyOf?.flatMap(option => option.required ?? []) ?? []);
  const optional = Object.keys(schema.properties ?? {}).filter(key => !required.includes(key) && !alternativeKeys.has(key));
  return `${parts.join(", ") || "None"}${optional.length ? `; optional: ${optional.join(", ")}` : ""}`;
}

